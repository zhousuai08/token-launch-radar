// Token Radar's model, written for this entry: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol on the snapshot's watchlist (the floor, never the ceiling) plus the
// pre-token protocols below the floor that pass the watchlist's own spirit: no exchange, no bridge,
// no wrapped or staked product of a token that already trades, no versioned pool. A protocol is
// pre-token when the snapshot records no token for it at all (no market cap, no CoinGecko id, no
// symbol). The snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value comes only from the snapshot's own figures, the same function for every row:
//
//   multiple  = the median mcap/TVL of the listed protocols in the row's own category, when at
//               least three of them trade; otherwise the median across every listed protocol.
//               Clamped to [0.05, 1.00], so one thin category cannot set the price.
//   growth    = clamp(change_7d, -40, +60) per cent; growthMult = 1 + growth/100 x 0.5
//   maturity  = 0.70 + min(age_days, 1095)/1095 x 0.30 (age unknown: 0.85)
//   implied   = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// No protocol name is ever special-cased. The multiples are computed from the snapshot at run time,
// so the board is a reading of this snapshot, not a list written in advance. A token's implied value
// is an estimate of what it would be worth if it launched with the record unchanged; it is not a
// prediction that it launches, or when.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
