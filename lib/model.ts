  growth_weight: 0.5,
  growth_floor: -40,
  growth_cap: 60,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  unknown_maturity: 0.85,
  min_category_n: 3,
  min_multiple: 0.05,
  max_multiple: 1.0,
