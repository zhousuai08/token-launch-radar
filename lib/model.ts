  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_maturity: number;
  min_category_n: number;
  min_multiple: number;
  max_multiple: number;
